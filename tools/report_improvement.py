"""Verify the benchmark against official reports and write the KPI comparison."""
from __future__ import annotations

import csv
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    reports = ROOT / 'reports'
    baseline = json.loads((reports / 'kpi_best_fit_windows.json').read_text(encoding='utf-8'))
    improved = json.loads((reports / 'kpi_improved_windows.json').read_text(encoding='utf-8'))
    experiments = list(csv.DictReader((reports / 'packing_benchmark.csv').read_text(encoding='utf-8-sig').splitlines()))
    by_key = {(r['test'], r['strategy']): r for r in experiments}
    regular = [r for r in experiments if r['test'].startswith('synthetic_') and r['strategy']=='improved']
    assert len(regular) == 16
    assert all(float(r['kpi']) > float(by_key[r['test'],'best_fit']['kpi']) for r in regular)
    assert improved['all_valid'] and improved['test_count'] == 15
    assert hashlib.sha256((ROOT / 'solution.cpp').read_bytes()).hexdigest() == improved['source_sha256']
    rows = []
    for old, new in zip(baseline['tests'], improved['tests'], strict=True):
        assert old['test'] == new['test'] and old['test_sha256'] == new['test_sha256']
        assert new['kpi'] >= old['kpi']
        for strategy, official in [('best_fit', old), ('improved', new)]:
            offline = by_key[str(new['test']), strategy]
            assert int(offline['trench_m']) == official['trench_m']
            assert math.isclose(float(offline['kpi']), official['kpi'], abs_tol=1e-13)
        peak = int(by_key[str(new['test']), 'improved']['peak_pipe_m'])
        minimum = ((peak + 19) // 20) * 20
        rows.append(dict(test=new['test'], final_m=new['remaining_pipe_m'], peak_m=peak,
                         min_trench_m=minimum, baseline_trench_m=old['trench_m'],
                         improved_trench_m=new['trench_m'], baseline_kpi=old['kpi'],
                         improved_kpi=new['kpi'], delta_kpi=new['kpi']-old['kpi'],
                         kpi_upper_bound=new['remaining_pipe_m']/minimum,
                         weight=new['weight'], improved_cpu_s=new['cpu_seconds']))
    with (reports / 'kpi_improvement.csv').open('w', encoding='utf-8', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader(); writer.writerows(rows)

    text = f'''# Улучшение Best Fit: разбор публичных тестов

Дата: 17 октября 2026 года. Основное решение: `solution.cpp`, GCC C++20.

Официальный интерактор принял **15/15 тестов**. Сумма баллов: **{baseline['total_weighted_score']:.12f} → {improved['total_weighted_score']:.12f}**.
Выигрыш — **{improved['total_weighted_score']-baseline['total_weighted_score']:.12f}** балла. Улучшены тесты 3, 5, 9, 10; KPI остальных сохранён.
Это локальные результаты на публичных данных; скрытые тесты и языковой бонус не включены.

`KPI = оставшиеся метры труб / выкопанные метры траншеи`. В таблице KPI без весов.

| Тест | Best Fit: траншея, м | Новое: траншея, м | Best Fit: KPI | Новое: KPI |
|---:|---:|---:|---:|---:|
'''
    for r in rows:
        text += f"| {r['test']} | {r['baseline_trench_m']} | {r['improved_trench_m']} | {r['baseline_kpi']:.6f} | {r['improved_kpi']:.6f} |\n"
    text += '''
## Почему ломается Best Fit

**Тест 3 — точное заполнение мешает объединить соседние участки.**
Сначала приходят `4, 4, 3, 4, 2, 3`: ровно 20 м. После удаления PID 1, 3, 5 остаются дыры длиной 4, 3, 2 м.
Следующую трубу длиной 2 м Best Fit ставит в точную дыру на позиции 15. Затем удаляется PID 6 длиной 3 м на позиции 17.
Из-за только что вставленной трубы получить свободные 5 м уже нельзя, и для следующей трубы 5 м приходится копать ещё 20 м.
Новый алгоритм кладёт двойку на позицию 0; после удаления PID 6 объединяются 2+3 м на правом краю. Итог: траншея 20 м, KPI 15/20 = 0,75.

**Тест 4 — низкий KPI вызван обязательной пиковой нагрузкой.**
Первые десять труб занимают 54 м. Поэтому любой алгоритм обязан выкопать минимум `ceil(54/20)*20 = 60` м.
В конце остаётся 40 м труб, и верхняя граница KPI равна 40/60 = 0,666667. Best Fit уже достигает её.
Поднять KPI до 1 здесь нельзя: траншея после удалений не сокращается.

**Тест 5 — удаляется каждая вторая труба, а следующая серия длиннее.**
Есть 40 серий с длинами от 1 до 40. В каждой приходят 125 одинаковых труб, затем удаляются 63 трубы с нечётным номером внутри серии.
Остаются 62 трубы, разделённые маленькими дырами. Следующая длина больше, поэтому обычный Best Fit почти не использует эти дыры.
Распределение длин само по себе этого не показывает: важно, какие трубы удаляются и какие участки после этого объединяются.

**Тест 9 — та же проблема с удвоением длины.**
Серии имеют длины 1, 2, 4, 8, 16, 32. В каждой — 1000 поступлений и удаление каждой второй трубы.
Одиночные освобождённые участки вдвое короче новой трубы. Новое размещение группирует очередные чётные и нечётные трубы у разных краёв свободного участка.
После удаления одной группы появляются крупные непрерывные дыры, подходящие следующей серии.

**Тест 10 — повторяющаяся ловушка с дырой в 1 м.**
Начальная серия — 769 повторений `3, 5, 2, 5, 1, 3, 1`, по 20 м в каждом блоке.
Затем удаляются первая, третья и пятая трубы каждого блока, то есть длины 3, 2 и 1.
Далее повторяется: добавить 1, удалить шестую трубу исходного блока длиной 3, добавить 4.
Best Fit кладёт единицу в точную дыру рядом с этой тройкой и блокирует объединение 1+3.
Новая оценка оставляет такую дыру свободной, а единицу помещает в менее опасный участок. Траншея больше не растёт: KPI 12304/15380 = 0,8.

## Проверка границ качества

Если максимальная одновременно занятая длина равна P, траншея не может быть короче `20*ceil(P/20)`.
Следовательно, `конечная занятость / (20*ceil(P/20))` — оптимистическая верхняя граница KPI.
Она учитывает пик нагрузки, но не доказывает, что такую укладку можно построить без перемещения труб.

| Тест | Конечная занятость, м | Пик, м | Верхняя граница KPI | Полученный KPI |
|---:|---:|---:|---:|---:|
'''
    for r in rows:
        if r['test'] in (3,4,5,9,10):
            text += f"| {r['test']} | {r['final_m']} | {r['peak_m']} | {r['kpi_upper_bound']:.6f} | {r['improved_kpi']:.6f} |\n"
    text += '''
На тестах 3, 4 и 10 достигнута эта верхняя граница. На 5 и 9 остаётся запас.

## Что реализовано

1. **Обычный Best Fit по умолчанию.** Два индекса свободных промежутков, использование хвоста перед расширением, объединение свободных соседей после удаления.
2. **Сохранение возможности объединения после массового удаления.** Если подряд удалено минимум 3 трубы и минимум четверть от числа активных труб перед серией удалений, включается временная оценка соседей. Она действует на следующие N поступлений, где N — число активных труб перед этим удалением. Новое массовое удаление обновляет срок.
3. **Оценка участка:** `score = (длина дыры - длина трубы) + 5*(r_левого_соседа + r_правого_соседа)`, где `r_l = число удалённых труб длины l / число ранее поступивших труб длины l`. На границе траншеи отсутствующий сосед даёт 0. Это эвристическая оценка риска, а не достоверная вероятность следующего удаления. Проверяется левый участок каждой длины, не более 11 кандидатов; при равенстве сохраняется Best Fit.
4. **Группировка серий после наблюдения закономерности.** Предыдущая серия должна состоять минимум из 32 труб одной длины; после неё удаляется минимум треть труб, все одной чётности внутри этой серии, без удаления труб других серий. В следующей однородной серии укладываем трубы поочерёдно от левого и правого края выбранного промежутка. Группы разной чётности перестают перемешиваться внутри участка. Это работает при удалении любой из двух чётностей.
5. **Ограниченное резервирование.** Только когда подходящей дыры нет, для такой серии можно выкопать немного больше минимального. Прогноз количества труб: минимум из оставшегося размера предыдущей серии, `2*число_уже_увиденных_труб-1` и 256. Дополнительное свободное место ограничено `max(20 м, 10% текущей траншеи)`, плюс максимум 19 м округления. На первой трубе новой серии прогноз равен 1, поэтому лишнего расширения нет. Изменение длины или превышение прошлого размера серии выключает эту группировку.

Оценка соседей не используется одновременно с группировкой однородной серии. Все решения зависят только от уже полученных команд.
Номера тестов, будущие команды, фиксированные размеры 125/1000 и исходные файлы в решении не используются.
Память — O(P+G), поиск — не более O(11 log G + 11 log P), где P — число труб, G — число дыр.

## Отдельный вклад двух изменений

В `reports/packing_benchmark.csv` сохранены четыре режима одной реализации. Базовый режим дополнительно сверяется с независимой метровой моделью.
Числа для базового и окончательного режимов совпали с официальными прогонами по всем 15 тестам.

| Режим | Сумма взвешенных KPI |
|---|---:|
'''
    for strategy, label in [('best_fit','Best Fit'),('cohorts_only','Только группировка серий'),('coalescence_only','Только оценка соседей после массового удаления'),('improved','Оба изменения')]:
        score = sum(float(r['weighted_score']) for r in experiments if r['test'].isdigit() and r['strategy']==strategy)
        text += f'| {label} | {score:.12f} |\n'
    max_cpu = max(r['cpu_seconds'] for r in improved['tests'])
    max_memory = max(r['peak_memory_mib'] for r in improved['tests'])
    text += f'''
## Проверки и ограничения вывода

- Официальный интерактор: 15/15 корректных тестов; CPU максимум **{max_cpu:.6f} с**, пиковый рабочий набор максимум **{max_memory:.2f} МиБ**. В этом Windows-прогоне все тесты уложились в 5 с и 256 МиБ. Показатели сервера могут отличаться.
- Независимая метровая модель: 40 случайных потоков по 1500 команд, каждый проверен новым алгоритмом и чистым Best Fit; отдельно 8 потоков с сериями других размеров, удалением обеих чётностей и сменой режима.
- Те же модульные проверки прошли в Linux/WSL под AddressSanitizer и UBSan, включая проверку утечек памяти.
- Отдельно: 200000 труб максимальной длины, некорректные PID/длины, повторное удаление, объединение двух соседей, хвост, немедленные ответы, фрагменты команд, CRLF, EOF, остановка на 0 и 10000 команд через границы входного буфера.
- Дополнительный KPI-прогон: серии по 47, 126, 257, 511 труб с другими длинами, удалением любой чётности и переходом к смешанному потоку. Во всех 16 таких сценариях новый KPI выше базового. Это синтетическая проверка, а не доказательство качества на скрытых данных.
- Есть и контрпример: после 65 единичных труб и удаления нечётных PID новая серия может оборваться уже на двух трубах длиной 40. Тогда прогноз оставляет лишнее место: точные результаты приведены ниже. Ограничение резервирования уменьшает потери, но не устраняет риск смены режима.

| Оборванная новая серия | Best Fit: траншея, м | Новое: траншея, м | Best Fit: KPI | Новое: KPI |
|---|---:|---:|---:|---:|
'''
    for name in ('forecast_stop_1','forecast_stop_2'):
        old,new=by_key[name,'best_fit'],by_key[name,'improved']
        text += f"| {name} | {old['trench_m']} | {new['trench_m']} | {float(old['kpi']):.6f} | {float(new['kpi']):.6f} |\n"
    text += f'''
Старое решение со статистикой длин сохранено в `solution_statistics.cpp`, его проверки — в `solution_statistics_test.cpp`.
Чистый Best Fit сохранён в `solution_best_fit.cpp`. Предыдущие отчёты остаются историческими.

## Воспроизведение

```powershell
.\\build_cpp.ps1 -Test
python tools/check_open_tests.py --source solution.cpp --report reports/kpi_improved_windows.json
g++ -std=c++20 -O2 -Wall -Wextra -Wpedantic -static tools/benchmark_packing.cpp -o build/benchmark-packing.exe
.\\build\\benchmark-packing.exe | Set-Content -Encoding utf8 reports/packing_benchmark.csv
python tools/report_improvement.py
```

Для g++ нужен компилятор в PATH; `build_cpp.ps1` самостоятельно находит локальный `.tools/w64devkit/bin/g++.exe`.
Официальный JSON: `reports/kpi_improved_windows.json`; сравнение CSV: `reports/kpi_improvement.csv`.
SHA-256 окончательного исходника: `{improved['source_sha256']}`.
'''
    (ROOT / 'BEST_FIT_IMPROVEMENT.md').write_text(text, encoding='utf-8', newline='\n')
    print('Verified 30 official/benchmark rows; wrote BEST_FIT_IMPROVEMENT.md and reports/kpi_improvement.csv')


if __name__ == '__main__':
    main()
